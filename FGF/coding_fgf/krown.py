"""KROWN-style controlled data-shape perturbations for RODI scenarios (optional).

KROWN (Van Assche, Chaves-Fraga, Dimou, ISWC 2024) benchmarks RDF materialisation with
a generator that changes one dataset parameter at a time. FGF is scored on correctness
rather than speed, so this module ports the four data-shape knobs that can change what
a generated FGF should emit:

* ``rows``       -- keep a fraction of the rows of root tables (tables without FKs to
                    other tables). Child tables keep only rows whose FK targets survive,
                    so referential integrity holds.
* ``nulls``      -- KROWN "empty values": a fraction of cells in nullable, non-key
                    columns is set to NULL.
* ``duplicates`` -- KROWN "duplicate values": a fraction of cells in non-key columns is
                    replaced by a value drawn from the same column. Primary, foreign and
                    unique columns are never touched, so keys stay valid.
* ``columns``    -- ``k`` extra unused text columns are added to every table (KROWN's
                    "number of columns").

Each generated scenario applies exactly one knob at one level (one change at a time).
The ``queries/`` directory and the ontology are copied unchanged. The reference SQL is
executed live against the loaded database by ``evaluate_graph``, so reference answers
follow the perturbed data. The SPARQL side is unchanged.

Not ported: KROWN's join-count knob (RODI schemas are fixed, so join count would need
schema restructuring) and cell-size knob (not a correctness-relevant change for FGF).

The data seed is fixed (``DATA_SEED``), so a given (scenario, knob, level) always yields
the same database. Repeat seeds for the LLM pipeline belong to the runner, not here.

Usage::

    python -m coding_fgf.krown create --rodi-root <RODI> --scenario cmt_renamed \\
        --out-root <OUT> [--spec rows:0.5 --spec nulls:0.2 ...]

Without ``--spec`` the default grid ``DEFAULT_GRID`` is generated.
"""

from __future__ import annotations

import argparse
import json
import random
import shutil
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Optional, Union

from .dump_edit import CopyBlock, render_dump, scan_copies, unique_columns
from .robustness import copy_base_scenario, scenario_source
from .schema import Table, foreign_key_columns, parse_sql_dump

KNOBS = ("rows", "nulls", "duplicates", "columns")
Level = Union[int, float]

# (knob, level) pairs generated by default. These levels are a starting point and are
# not from the report. Change them with --spec.
DEFAULT_GRID: tuple[tuple[str, Level], ...] = (
    ("rows", 0.5),
    ("rows", 0.25),
    ("nulls", 0.2),
    ("nulls", 0.5),
    ("duplicates", 0.2),
    ("duplicates", 0.5),
    ("columns", 4),
    ("columns", 12),
)

DATA_SEED = 0
FILLER_PREFIX = "krown_filler_"
MAX_FILLER_COLUMNS = 50


# ---------------------------------------------------------------------------
# Specs
# ---------------------------------------------------------------------------

def validate_spec(knob: str, level: Level) -> tuple[str, Level]:
    """Return a normalised (knob, level). Raises ValueError for unknown knobs or bad levels."""
    if knob not in KNOBS:
        raise ValueError(f"unknown KROWN knob {knob!r}; expected one of {KNOBS}")
    if knob == "columns":
        if float(level) != int(level) or not 1 <= int(level) <= MAX_FILLER_COLUMNS:
            raise ValueError(f"columns level must be an integer in [1, {MAX_FILLER_COLUMNS}], got {level!r}")
        return knob, int(level)
    value = float(level)
    if knob == "rows" and not 0.0 < value <= 1.0:
        raise ValueError(f"rows level must be in (0, 1], got {level!r}")
    if knob in ("nulls", "duplicates") and not 0.0 < value < 1.0:
        raise ValueError(f"{knob} level must be in (0, 1), got {level!r}")
    return knob, value


def level_tag(knob: str, level: Level) -> str:
    if knob == "columns":
        return f"k{int(level)}"
    return f"p{round(float(level) * 100)}"


def scenario_name(scenario: str, knob: str, level: Level) -> str:
    return f"{scenario}__krown_{knob}_{level_tag(knob, level)}"


def parse_spec(text: str) -> tuple[str, Level]:
    """Parse a ``knob:level`` command-line spec such as ``rows:0.5`` or ``columns:4``."""
    knob, sep, raw = text.partition(":")
    if not sep:
        raise ValueError(f"spec must look like knob:level, got {text!r}")
    level: Level = int(raw) if knob == "columns" and raw.isdigit() else float(raw)
    return validate_spec(knob, level)


# ---------------------------------------------------------------------------
# Knob implementations (each mutates the copy blocks in place and returns stats)
# ---------------------------------------------------------------------------

def _self_references(tables: dict[str, Table]) -> list[tuple[str, tuple[str, ...]]]:
    """FKs from a table to itself. The rows knob does not enforce these."""
    return [
        (name, tuple(fk.columns))
        for name, table in tables.items()
        for fk in table.foreign_keys
        if fk.ref_table == name
    ]


def _apply_rows(
    tables: dict[str, Table], copies: dict[str, CopyBlock], fraction: float, rng: random.Random
) -> dict[str, Any]:
    """Sample each table to ``fraction`` of its rows, then prune rows that break an FK.

    Pruning is repeated until no row is removed. The result is a greatest fixpoint: every
    kept row with a non-NULL FK value has a kept parent. This also handles FK cycles,
    which RODI schemas contain. Removals can cascade, so the per-table before/after
    counts in the manifest matter when reading results.
    """
    before = {name: len(block.rows) for name, block in copies.items()}
    for name in sorted(copies):
        block = copies[name]
        k = round(fraction * len(block.rows))
        chosen = sorted(rng.sample(range(len(block.rows)), k))
        block.rows = [block.rows[i] for i in chosen]
    sampled = {name: len(block.rows) for name, block in copies.items()}

    # A parent table with no COPY block is empty, so child rows that reference it must go.
    fk_specs: list[tuple[str, Any]] = []
    for name, table in tables.items():
        if name not in copies:
            continue
        for fk in table.foreign_keys:
            if fk.ref_table != name and fk.ref_table in tables:
                fk_specs.append((name, fk))

    changed = True
    while changed:
        changed = False
        key_cache: dict[tuple[str, tuple[str, ...]], set[tuple[Optional[str], ...]]] = {}
        for name, fk in fk_specs:
            parent_key = (fk.ref_table, tuple(fk.ref_columns))
            if parent_key not in key_cache:
                pblock = copies.get(fk.ref_table)
                if pblock is None:
                    key_cache[parent_key] = set()
                else:
                    pidx = {c: i for i, c in enumerate(pblock.header)}
                    key_cache[parent_key] = {tuple(r[pidx[c]] for c in fk.ref_columns) for r in pblock.rows}
            keys = key_cache[parent_key]
            block = copies[name]
            cidx = {c: i for i, c in enumerate(block.header)}
            kept = []
            for row in block.rows:
                values = tuple(row[cidx[c]] for c in fk.columns)
                if None in values or values in keys:
                    kept.append(row)
                else:
                    changed = True
            block.rows = kept
    per_table = {
        name: {"before": before[name], "after_sampling": sampled[name], "after": len(copies[name].rows)}
        for name in sorted(copies)
    }
    return {
        "per_table": per_table,
        "rows_removed": sum(v["before"] - v["after"] for v in per_table.values()),
    }


def _apply_nulls(
    tables: dict[str, Table], copies: dict[str, CopyBlock], fraction: float, rng: random.Random
) -> dict[str, Any]:
    changed = 0
    per_column: dict[str, int] = {}
    for name in sorted(tables):
        block = copies.get(name)
        if block is None:
            continue
        table = tables[name]
        protected = set(table.primary_key) | foreign_key_columns(table)
        index = {c: i for i, c in enumerate(block.header)}
        for column in table.columns:
            if not column.nullable or column.name in protected or column.name not in index:
                continue
            idx = index[column.name]
            count = 0
            for row in block.rows:
                if rng.random() < fraction and row[idx] is not None:
                    row[idx] = None
                    count += 1
            per_column[f"{name}.{column.name}"] = count
            changed += count
    return {"cells_nulled": changed, "per_column": per_column}


def _apply_duplicates(
    tables: dict[str, Table],
    copies: dict[str, CopyBlock],
    fraction: float,
    rng: random.Random,
    unique: dict[str, set[str]],
) -> dict[str, Any]:
    changed = 0
    per_column: dict[str, int] = {}
    for name in sorted(tables):
        block = copies.get(name)
        if block is None or len(block.rows) < 2:
            continue
        table = tables[name]
        protected = set(table.primary_key) | foreign_key_columns(table) | unique.get(name, set())
        index = {c: i for i, c in enumerate(block.header)}
        for column in table.columns:
            if column.name in protected or column.name not in index:
                continue
            idx = index[column.name]
            pool = [row[idx] for row in block.rows if row[idx] is not None]
            if not pool:
                continue
            count = 0
            for row in block.rows:
                if rng.random() < fraction:
                    row[idx] = rng.choice(pool)
                    count += 1
            per_column[f"{name}.{column.name}"] = count
            changed += count
    return {"cells_duplicated": changed, "per_column": per_column}


def _apply_columns(
    tables: dict[str, Table],
    copies: dict[str, CopyBlock],
    count: int,
) -> dict[str, list[str]]:
    """Add ``count`` filler columns to every table, with NULL values.

    NULL values keep the content identical to the base, so only the table width changes.
    Names carry the table name (``<table>_krown_filler_<i>``). A shared name would become
    a join key for NATURAL JOIN and USING queries, which changes the reference answers.
    """
    extra: dict[str, list[str]] = {}
    for name in sorted(tables):
        names = [f"{name}_{FILLER_PREFIX}{i}" for i in range(1, count + 1)]
        clash = set(tables[name].column_names()) & set(names)
        if clash:
            raise ValueError(f"table {name} already has columns named {sorted(clash)}")
        extra[name] = names
        block = copies.get(name)
        if block is not None:
            for row in block.rows:
                row.extend([None] * len(names))
            block.header = block.header + names
    return extra


# ---------------------------------------------------------------------------
# Scenario generation
# ---------------------------------------------------------------------------

def make_krown_scenario(
    rodi_root: Path,
    scenario: str,
    out_root: Path,
    knob: str,
    level: Level,
) -> dict[str, Any]:
    """Write ``out_root/data/<scenario>__krown_<knob>_<level>`` and return its manifest."""
    knob, level = validate_spec(knob, level)
    src = scenario_source(rodi_root, scenario)
    dump_path = src / "dump.sql"
    text = dump_path.read_text(encoding="utf-8", errors="replace")
    tables = parse_sql_dump(dump_path)
    lines = text.split("\n")
    copies = scan_copies(lines)
    for name in copies:
        if name not in tables:
            raise ValueError(f"COPY data for {name} has no CREATE TABLE in the dump")

    name = scenario_name(scenario, knob, level)
    rng = random.Random(f"{scenario}|{knob}|{level_tag(knob, level)}|{DATA_SEED}")
    extra_columns: dict[str, list[str]] = {}
    detail: dict[str, Any]
    if knob == "rows":
        detail = _apply_rows(tables, copies, float(level), rng)
    elif knob == "nulls":
        detail = _apply_nulls(tables, copies, float(level), rng)
    elif knob == "duplicates":
        detail = _apply_duplicates(tables, copies, float(level), rng, unique_columns(text))
    else:
        extra_columns = _apply_columns(tables, copies, int(level))
        detail = {"filler_columns_per_table": int(level), "filler_values": "NULL"}

    rendered = render_dump(lines, copies, extra_columns)

    dst = Path(out_root) / "data" / name
    if dst.exists():
        shutil.rmtree(dst)
    shutil.copytree(src, dst, ignore=shutil.ignore_patterns("dump.sql", ".DS_Store"))
    # Write LF explicitly so the output matches the RODI source dumps byte-for-byte in format.
    # (Windows text mode would otherwise write CRLF.)
    with open(dst / "dump.sql", "w", encoding="utf-8", newline="\n") as fh:
        fh.write(rendered)

    self_refs = _self_references(tables)
    manifest = {
        "generator": "krown",
        "scenario": scenario,
        "name": name,
        "knob": knob,
        "level": level,
        "data_seed": DATA_SEED,
        "unenforced_self_references": [{"table": t, "columns": list(c)} for t, c in self_refs],
        "detail": detail,
    }
    (dst / "krown_manifest.json").write_text(json.dumps(manifest, indent=2, sort_keys=True), encoding="utf-8")
    return manifest


def _cmd_create(args: argparse.Namespace) -> None:
    specs = [parse_spec(s) for s in args.spec] if args.spec else list(DEFAULT_GRID)
    out_root = Path(args.out_root)
    base = copy_base_scenario(Path(args.rodi_root), args.scenario, out_root)
    print(f"{args.scenario}: copied unperturbed scenario to {base}")
    for knob, level in specs:
        manifest = make_krown_scenario(Path(args.rodi_root), args.scenario, out_root, knob, level)
        print(f"{manifest['name']}: knob={knob} level={level}")


def main(argv: Optional[list[str]] = None) -> None:
    parser = argparse.ArgumentParser(description="KROWN-style data-shape perturbations for RODI scenarios.")
    sub = parser.add_subparsers(dest="command", required=True)
    create = sub.add_parser("create", help="Write KROWN-perturbed RODI scenario copies.")
    create.add_argument("--rodi-root", required=True, help="Directory containing data/<scenario>.")
    create.add_argument("--scenario", required=True)
    create.add_argument("--out-root", required=True, help="Root that will be passed as --rodi-root to the pipeline.")
    create.add_argument(
        "--spec",
        action="append",
        default=[],
        help="knob:level, repeatable. Knobs: rows, nulls, duplicates, columns. Default: DEFAULT_GRID.",
    )
    create.set_defaults(func=_cmd_create)
    args = parser.parse_args(argv)
    args.func(args)


if __name__ == "__main__":
    main()
